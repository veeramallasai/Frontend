  static List<Map<String, dynamic>> get products {
    return _products.map((Map<String, dynamic> product) {
      final String imageRoot = product['imageRoot']?.toString() ?? '';
      final String file = product['file']?.toString() ?? '';

      return <String, dynamic>{
        ...product,
        'image': '$imageRoot$file',
      };
    }).toList(growable: false);
  }

  static List<Map<String, dynamic>> productsByCategory(String category) {
    final String target = normalizedName(category);

    return products.where((Map<String, dynamic> product) {
      return normalizedName(product['category']?.toString() ?? '') == target;
    }).toList(growable: false);
  }

  static List<Map<String, dynamic>> productsByCollection(String collection) {
    final String target = normalizedName(collection);

    return products.where((Map<String, dynamic> product) {
      return normalizedName(product['collection']?.toString() ?? '') == target;
    }).toList(growable: false);
  }

  static List<Map<String, dynamic>> get bestSellers {
    return products
        .where((Map<String, dynamic> product) => product['bestSeller'] == true)
        .toList(growable: false);
  }

  static List<Map<String, dynamic>> get quickDeliveryProducts {
    return products
        .where((Map<String, dynamic> product) => product['isQuick'] == true)
        .toList(growable: false);
  }

  static List<Map<String, dynamic>> get organicProducts {
    return products
        .where((Map<String, dynamic> product) => product['organic'] == true)
        .toList(growable: false);
  }

  static List<Map<String, dynamic>> get discountedProducts {
    final List<Map<String, dynamic>> result = products
        .where((Map<String, dynamic> product) {
      final dynamic value = product['discount'];
      return value is num && value > 0;
    })
        .toList();

    result.sort((a, b) {
      final num first = a['discount'] is num ? a['discount'] as num : 0;
      final num second = b['discount'] is num ? b['discount'] as num : 0;
      return second.compareTo(first);
    });

    return result;
  }

  static Map<String, dynamic>? productById(String id) {
    final String target = id.trim();

    for (final Map<String, dynamic> product in products) {
      if (product['id']?.toString() == target) {
        return product;
      }
    }

    return null;
  }

  static Map<String, dynamic>? productByName(String name) {
    final String target = normalizedName(name);

    for (final Map<String, dynamic> product in products) {
      final String local = normalizedName(product['name']?.toString() ?? '');

      if (target == local ||
          target.contains(local) ||
          local.contains(target)) {
        return product;
      }
    }

    return null;
  }

  static String normalizedName(String value) {
    return value
        .toLowerCase()
        .replaceAll(RegExp(r'[^a-z0-9]'), '');
  }

  static String imageFor({
    required String name,
    String? preferredImage,
  }) {
    if (preferredImage != null &&
        preferredImage.trim().isNotEmpty &&
        preferredImage.startsWith('assets/')) {
      return preferredImage;
    }

    final Map<String, dynamic>? match = productByName(name);

    if (match != null) {
      return match['image']?.toString() ?? preferredImage ?? '';
    }

    return preferredImage ?? '';
  }

  static String teluguNameFor(String name) {
    final Map<String, dynamic>? match = productByName(name);
    return match?['teluguName']?.toString() ?? '';
  }

  static String displayNameFor(String name) {
    final Map<String, dynamic>? match = productByName(name);

    if (match == null) {
      return name;
    }

    final String englishName = match['name']?.toString() ?? name;
    final String teluguName = match['teluguName']?.toString() ?? '';

    return teluguName.isEmpty
        ? englishName
        : '$englishName ($teluguName)';
  }

  static String categoryTeluguFor(String category) {
    switch (normalizedName(category)) {
      case 'vegetables':
        return 'కూరగాయలు';
      case 'fruits':
        return 'పండ్లు';
      case 'dairy':
        return 'పాల ఉత్పత్తులు';
      default:
        return '';
    }
  }
